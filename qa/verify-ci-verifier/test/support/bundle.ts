const made: string[] = [];
export function cleanup(): void { for (const d of made.splice(0)) rmSync(d, { recursive: true, force: true }); }
/** Fresh private copy of the real scenario bundle. */
export function fresh(count: Count): string {
  const source = BUNDLE_ROOT ? join(BUNDLE_ROOT, `scenario-${count}`) : join(HISTORICAL_ROOT, count === 2 ? "1v1" : "2v2");
  const sha = BUNDLE_ROOT ? SHA : String((JSON.parse(readFileSync(join(source, "manifest.json"), "utf8")) as { sourceSha: string }).sourceSha);
  if (!sha) throw new Error("CI_QA_SHA is required when CI_QA_BUNDLE_ROOT is set");
  const dir = mkdtempSync(join(tmpdir(), `ciqa-${count}-`)); made.push(dir);
  cpSync(source, dir, { recursive: true });
  shaByDir.set(dir, sha);
  return dir;
}
export const readJson = <T = Record<string, any>>(dir: string, file: string): T => JSON.parse(readFileSync(join(dir, file), "utf8")) as T;
export const writeJson = (dir: string, file: string, value: unknown): void => writeFileSync(join(dir, file), JSON.stringify(value, null, 2));
export const readRows = (dir: string): Row[] => readFileSync(join(dir, "operator.jsonl"), "utf8").split(/\r?\n/).filter((l) => l.trim()).map((l) => JSON.parse(l) as Row);
export const receiptPath = (dir: string, id: string): string => join(dir, "receipts", `${id}.json`);

/** Rewrite the journal with a VALID hash chain (the attacker recomputes everything), and keep verdict.json's journal digest in step. */
export function writeRowsRehashed(dir: string, rows: Row[], opts: { fixVerdictDigest?: boolean } = {}): void {
  let prior = "";
  const lines = rows.map((r, i) => {
    const copy: Record<string, unknown> = { ...r, seq: i + 1, previousHash: prior };
    delete copy.hash;
    const hash = computeJournalRowHash(copy);
    prior = hash;
    return JSON.stringify({ ...copy, hash });
  });
  const text = lines.join("\n") + "\n";
  writeFileSync(join(dir, "operator.jsonl"), text);
  if (opts.fixVerdictDigest !== false) {
    const verdict = readJson(dir, "verdict.json");
    verdict.evidenceJournalSha256 = createHash("sha256").update(Buffer.from(text)).digest("hex");
    writeJson(dir, "verdict.json", verdict);
  }
}

